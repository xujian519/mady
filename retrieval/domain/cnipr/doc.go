// Package cnipr 实现 CNIPR（search.cnipr.com）检索通道：关键词检索、按公开号取全文
// PDF 直链、按申请号/公开号查法律状态。
//
// 通道只做三件事：可用性检查、脚本运行、收据解析映射。页面交互在 scripts 生成的
// ego-browser 脚本里，判定与解析在本包的纯函数里（脚本以 stdin 交给 ego 执行，
// 只能在真实站点验证；因此脚本只回传页面原文，号码形态、记录字段与失败分类全部
// 由可单测的 Go 代码决定）。
//
// 失败分两类：号码级失败（某个号检索不到、解析不出申请号）按条目回报，不中断同批
// 其余号；通道级失败（ego 不可用、超时、脚本没回执、登录态失效）返回带分类的错误，
// 由调用方决定是否按号回退到别的通道。
